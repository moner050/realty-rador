def resolve_cortarno(region_name: str | None) -> str | None:
    """지역명(시/도, 구/시)을 입력받아 해당 시/도 또는 구/시의 cortarNo 코드를 반환."""
    if not region_name or region_name.strip() in ["전체", "서울 및 경기도", "서울/경기", "수동전체", "ALL", "all", ""]:
        return "ALL_METRO"

    name_clean = region_name.strip()

    # 정확한 시/도 매칭
    if name_clean in SIDO_CODES:
        return SIDO_CODES[name_clean]

    # 정확한 구/시 매칭
    for sido, sigungu_map in SIGUNGU_CODES.items():
        for sigungu_name, code in sigungu_map.items():
            if sigungu_name == name_clean or f"{sido} {sigungu_name}" == name_clean:
                return code

    # 포함 매칭 (전체 주소 텍스트 검색 지원)
    for sido, sigungu_map in SIGUNGU_CODES.items():
        for sigungu_name, code in sigungu_map.items():
            if sigungu_name in name_clean or name_clean in sigungu_name:
                return code

    # 부분 매칭
    for sido, code in SIDO_CODES.items():
        if name_clean in sido or sido in name_clean:
            return code

    return "ALL_METRO"


def get_all_sigungu_codes(sido: str | None = None) -> list[tuple[str, str, str]]:
    """(시/도, 구/시, cortarNo) 튜플 리스트 반환. sido 미지정 시 전체."""
    results = []
    for sido_name, sigungu_map in SIGUNGU_CODES.items():
        if sido and sido not in sido_name:
            continue
        for sigungu_name, code in sigungu_map.items():
            results.append((sido_name, sigungu_name, code))
    return results
